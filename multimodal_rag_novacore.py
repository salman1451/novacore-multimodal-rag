def chunk_documents(documents, chunk_size=CHUNK_SIZE, chunk_overlap=CHUNK_OVERLAP):
    """
    Split long TEXT documents into RAG-sized chunks. Tables and vision summaries
    are already compact/atomic units of meaning, so we pass them through unchanged
    and only chunk the raw page-text documents.
    """
    splitter = RecursiveCharacterTextSplitter(
        chunk_size=chunk_size,
        chunk_overlap=chunk_overlap,
    )

    chunked_documents = []

    for doc in documents:
        if doc.metadata.get("modality") == "text":
            splits = splitter.split_documents([doc])
            chunked_documents.extend(splits)
        else:
            chunked_documents.append(doc)

    return chunked_documents


