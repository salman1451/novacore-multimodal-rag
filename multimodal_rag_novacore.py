def get_or_create_pinecone_index(index_name, dimension, api_key):
    pc = Pinecone(api_key=api_key)

    if not pc.has_index(index_name):
        print("Creating Pinecone index...")
        pc.create_index(
            name=index_name,
            dimension=dimension,
            metric="cosine",
            spec=ServerlessSpec(cloud="aws", region="us-east-1"),
        )
        while not pc.describe_index(index_name).status["ready"]:
            print("Waiting for Pinecone index...")
            time.sleep(2)
        print("Pinecone index created.")
    else:
        print("Pinecone index already exists.")

    return pc.Index(index_name)


def build_vectorstore(chunked_documents, embeddings, index_name, namespace, api_key):
    """Clear the namespace, then embed + upsert all chunked documents."""
    index = get_or_create_pinecone_index(
        index_name=index_name,
        dimension=len(embeddings.embed_query("dimension check")),
        api_key=api_key,
    )
    print("Connected to:", index_name)

    try:
        index.delete(delete_all=True, namespace=namespace)
        print("Cleared namespace:", namespace)
    except Exception as error:
        print("Namespace was probably empty. Continuing...", error)

    vectorstore = PineconeVectorStore(
        index_name=index_name,
        embedding=embeddings,
        namespace=namespace,
    )
    vectorstore.add_documents(chunked_documents)
    print("Documents uploaded to Pinecone.")

    return vectorstore


