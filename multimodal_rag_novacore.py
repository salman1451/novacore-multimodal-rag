# STAGE 9: QUERY INTERFACE (end-to-end)
# =========================================================================

def ask_rag(question, retriever, show_sources=True, show_images=False):
    # Retrieve
    retrieved_docs = retriever.invoke(question)

    # Build context
    context = format_context(retrieved_docs)

    # Collect any visuals returned by retrieval
    image_paths = []
    for doc in retrieved_docs:
        if doc.metadata.get("modality") == "visual":
            image_path = doc.metadata.get("image_path")
            if image_path and Path(image_path).exists():
                image_paths.append(image_path)

    # Generate (route to vision-augmented chain if visuals were retrieved)
    if image_paths:
        answer = answer_with_vision(question=question, context=context, image_paths=image_paths)
    else:
        answer = text_rag_chain.invoke({"context": context, "question": question})

    print("\nQUESTION:")
    print(question)
    print("\nANSWER:")
    print(answer)

    if show_sources:
        print("\nPINECONE RETRIEVED SOURCES:")
        for i, doc in enumerate(retrieved_docs, start=1):
            print(f"{i}. Page {doc.metadata.get('page')} | {doc.metadata.get('modality')}")

    if show_images and image_paths:
        print("\nRETRIEVED VISUALS:")
        for image_path in image_paths:
            display(Image.open(image_path))

    return {"answer": answer, "documents": retrieved_docs, "image_paths": image_paths}


