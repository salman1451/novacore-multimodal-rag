def extract_text(page):
    """Pull raw text from one PDF page."""
    text = page.get_text("text").strip()
    return text if text else None


def create_text_document(text, page_number, source):
    return Document(
        page_content=text,
        metadata={"page": page_number, "modality": "text", "source": source},
    )


def extract_tables(page):
    """Pull tables from one PDF page and convert each to a markdown Document."""
    table_documents = []

    try:
        tables = page.find_tables().tables

        for table_number, table in enumerate(tables, start=1):
            df = table.to_pandas()
            if df.empty:
                continue

            table_text = df.to_markdown(index=False)
            document = Document(
                page_content=table_text,
                metadata={
                    "page": page.number + 1,
                    "modality": "table",
                    "table_number": table_number,
                },
            )
            table_documents.append(document)

    except Exception as error:
        print("Table extraction error:", error)

    return table_documents


def extract_images(page, pdf, image_dir, processed_images):
    """Pull images from one PDF page, save them, and describe them via the vision model."""
    image_documents = []
    page_number = page.number + 1
    images = page.get_images(full=True)

    for image_number, image_info in enumerate(images, start=1):
        xref = image_info[0]

        if xref in processed_images:  # skip duplicates
            continue
        processed_images.add(xref)

        image_data = pdf.extract_image(xref)
        image_bytes = image_data["image"]
        extension = image_data["ext"]

        image_path = image_dir / f"page_{page_number}_image_{image_number}.{extension}"
        image_path.write_bytes(image_bytes)

        try:
            summary = summarize_visual(image_path=image_path, page_number=page_number)

            document = Document(
                page_content=summary,
                metadata={
                    "page": page_number,
                    "modality": "visual",
                    "image_path": str(image_path),
                    "image_number": image_number,
                },
            )
            image_documents.append(document)

        except Exception as error:
            print(f"Vision error on page {page_number}:", error)

    return image_documents


def process_page(page, pdf, image_dir, processed_images, source):
    """Extract text + tables + images (with descriptions) from a single page."""
    documents = []
    page_number = page.number + 1
    print(f"Processing page {page_number}...")

    text = extract_text(page)
    if text:
        documents.append(create_text_document(text=text, page_number=page_number, source=source))

    table_documents = extract_tables(page)
    for document in table_documents:
        document.metadata["source"] = source
    documents.extend(table_documents)

    image_documents = extract_images(
        page=page, pdf=pdf, image_dir=image_dir, processed_images=processed_images
    )
    for document in image_documents:
        document.metadata["source"] = source
    documents.extend(image_documents)

    return documents


def load_and_extract_multimodal_documents(pdf_path, image_dir):
    """
    STAGE 1 (LOAD) + STAGE 2 (EXTRACT): open the PDF and walk every page,
    extracting text, tables, and vision-described images into Documents.
    """
    pdf_path = Path(pdf_path)
    image_dir = Path(image_dir)
    image_dir.mkdir(parents=True, exist_ok=True)

    pdf = fitz.open(str(pdf_path))
    all_documents = []
    processed_images = set()

    for page in pdf:
        page_documents = process_page(
            page=page,
            pdf=pdf,
            image_dir=image_dir,
            processed_images=processed_images,
            source=pdf_path.name,
        )
        all_documents.extend(page_documents)

    pdf.close()
    return all_documents


